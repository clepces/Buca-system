/**
 * IndexedDBDriver - Motor de Almacenamiento Estructurado
 * =========================================================================
 * Utiliza la API de IndexedDB para almacenamiento de alta capacidad.
 * No bloquea el hilo principal, ideal para Tier L2/L3.
 * =========================================================================
 */
export class IndexedDBDriver {
    constructor(dbName = 'buca_db', storeName = 'keyvalue') {
        this.dbName = dbName;
        this.storeName = storeName;
        this.db = null;
    }

    async _init() {
        if (this.db) return this.db;
        return new Promise((resolve, reject) => {
            const request = indexedDB.open(this.dbName, 1);
            request.onupgradeneeded = (e) => {
                const db = e.target.result;
                if (!db.objectStoreNames.contains(this.storeName)) {
                    db.createObjectStore(this.storeName);
                }
            };
            request.onsuccess = (e) => {
                this.db = e.target.result;
                resolve(this.db);
            };
            request.onerror = (e) => reject(e.target.error);
        });
    }

    async set(key, value) {
        const db = await this._init();
        return new Promise((resolve, reject) => {
            const tx = db.transaction(this.storeName, 'readwrite');
            const store = tx.objectStore(this.storeName);
            const request = store.put(value, key);
            request.onsuccess = () => resolve();
            request.onerror = () => reject(request.error);
        });
    }

    async get(key) {
        const db = await this._init();
        return new Promise((resolve, reject) => {
            const tx = db.transaction(this.storeName, 'readonly');
            const store = tx.objectStore(this.storeName);
            const request = store.get(key);
            request.onsuccess = () => resolve(request.result);
            request.onerror = () => reject(request.error);
        });
    }

    async remove(key) {
        const db = await this._init();
        return new Promise((resolve, reject) => {
            const tx = db.transaction(this.storeName, 'readwrite');
            const store = tx.objectStore(this.storeName);
            const request = store.delete(key);
            request.onsuccess = () => resolve();
            request.onerror = () => reject(request.error);
        });
    }
}

export default IndexedDBDriver;
